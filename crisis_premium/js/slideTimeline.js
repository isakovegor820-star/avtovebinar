export function hasVerifiedTimeline(timeline) {
  return Array.isArray(timeline)
    && timeline.length === EXPECTED_SLIDE_COUNT
    && timeline[0]?.at === 0
    && timeline.every((slide, index) => (
      Number.isFinite(slide?.at)
      && slide.at >= 0
      && slide.at < WEBINAR_DURATION_SECONDS
      && typeof slide.title === 'string'
      && slide.title.trim().length > 0
      && (index === 0 || slide.at > timeline[index - 1].at)
    ));
}

export function slideIndexForTime(seconds, timeline = VERIFIED_SLIDES) {
  const time = Number.isFinite(seconds) ? Math.max(0, seconds) : 0;
  let low = 0;
  let high = timeline.length - 1;

  while (low < high) {
    const middle = Math.ceil((low + high) / 2);
    if (time >= timeline[middle].at) low = middle;
    else high = middle - 1;
  }

  return low;
}
